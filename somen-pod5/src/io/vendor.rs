use std::error::Error;
use std::fmt::{Display, Formatter};
use std::io::Read;

mod vbz_fused;

/// A POD5 VBZ payload is a Zstandard frame containing delta/zigzag SVB16.
/// Its sample count is stored separately in the POD5 signal table.
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub enum VendorError {
    MissingSampleCount,
    InvalidZstd,
    InvalidSignal,
    SampleCountTooLarge,
}

impl Display for VendorError {
    fn fmt(&self, f: &mut Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::MissingSampleCount => write!(f, "POD5 VBZ decoding requires the signal sample count"),
            Self::InvalidZstd => write!(f, "invalid Zstandard signal frame"),
            Self::InvalidSignal => write!(f, "invalid SVB16 signal payload"),
            Self::SampleCountTooLarge => write!(f, "signal sample count is too large"),
        }
    }
}
impl Error for VendorError {}

/// The legacy interface cannot decode POD5 VBZ without the sample count.
pub fn decode(_data: &[u8]) -> Result<Vec<i16>, VendorError> {
    Err(VendorError::MissingSampleCount)
}

/// Decode a POD5 VBZ frame using the corresponding signal table sample count.
pub fn decode_with_count(data: &[u8], n: usize) -> Result<Vec<i16>, VendorError> {
    let max_len = n.checked_mul(2).and_then(|v| v.checked_add(n.div_ceil(8)))
        .ok_or(VendorError::SampleCountTooLarge)?;
    let limit = u64::try_from(max_len).ok().and_then(|v| v.checked_add(1))
        .ok_or(VendorError::SampleCountTooLarge)?;
    let decoder = ruzstd::decoding::StreamingDecoder::new(data).map_err(|_| VendorError::InvalidZstd)?;
    let mut payload = Vec::new();
    decoder.take(limit).read_to_end(&mut payload).map_err(|_| VendorError::InvalidZstd)?;
    if payload.len() > max_len {
        return Err(VendorError::InvalidSignal);
    }
    let mut out = Vec::new();
    out.try_reserve_exact(n).map_err(|_| VendorError::SampleCountTooLarge)?;
    vbz_fused::decode_into(&payload, n, &mut out).map_err(|_| VendorError::InvalidSignal)?;
    Ok(out)
}

/// Encode samples as a POD5-compatible Zstandard-wrapped SVB16 stream.
pub fn encode(data: &[i16]) -> Vec<u8> {
    let payload = vbz_fused::encode(data);
    // POD5's reference decoder requires the Zstandard frame content size.
    // `ruzstd`'s streaming encoder omits it, whereas this one-shot API includes it.
    zstd::bulk::compress(&payload, 1).expect("in-memory Zstandard compression failed")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn decodes_official_pod5_reference_vector() {
        // Generated by pod5 0.3.36 vbz_compress_signal for these six values.
        let frame = [0x28, 0xb5, 0x2f, 0xfd, 0x20, 0x08, 0x41, 0x00, 0x00,
            0x10, 0x00, 0x01, 0x04, 0xfe, 0x00, 0xff, 0x01];
        assert_eq!(decode_with_count(&frame, 6).unwrap(), [0, -1, 1, 128, i16::MIN, i16::MAX]);
        let encoded = encode(&[0, -1, 1, 128, i16::MIN, i16::MAX]);
        assert_eq!(zstd::zstd_safe::get_frame_content_size(&encoded).unwrap(), Some(8));
    }

    #[test]
    fn zstd_wrapped_svb_round_trip() {
        for samples in [&[][..], &[0, -1, 1, 128, i16::MIN, i16::MAX][..]] {
            let encoded = encode(samples);
            assert_eq!(&encoded[..4], &[0x28, 0xb5, 0x2f, 0xfd]);
            assert_eq!(decode_with_count(&encoded, samples.len()).unwrap(), samples);
        }
    }

    #[test]
    fn rejects_missing_count_and_invalid_payloads() {
        assert_eq!(decode(&[]), Err(VendorError::MissingSampleCount));
        assert_eq!(decode_with_count(&[], 1), Err(VendorError::InvalidZstd));
        let short = ruzstd::encoding::compress_to_vec(&[0u8][..], ruzstd::encoding::CompressionLevel::Fastest);
        assert_eq!(decode_with_count(&short, 1), Err(VendorError::InvalidSignal));
        let too_long = ruzstd::encoding::compress_to_vec(&[0u8; 4][..], ruzstd::encoding::CompressionLevel::Fastest);
        assert_eq!(decode_with_count(&too_long, 1), Err(VendorError::InvalidSignal));
    }
}
